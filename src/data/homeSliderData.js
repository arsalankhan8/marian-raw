/** Canada, US, Canada, US, … then remaining Canada slides when US list ends. */
export const mergeAlternatingSlides = (canadaSlides, usSlides) => {
  const merged = [];
  const maxLen = Math.max(canadaSlides.length, usSlides.length);

  for (let i = 0; i < maxLen; i += 1) {
    if (i < canadaSlides.length) merged.push(canadaSlides[i]);
    if (i < usSlides.length) merged.push(usSlides[i]);
  }

  return merged;
};

export const CANADA_HOME_MERGED_SLIDES = mergeAlternatingSlides(
  CANADA_HOME_SLIDES,
  US_HOME_SLIDES,
);
